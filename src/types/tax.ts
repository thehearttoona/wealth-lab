/** ยอดที่ผู้ใช้กรอกต่อรายการ (คีย์ = DeductionItem.key) */
export type DeductionMap = { [key: string]: number };

export interface DeductionResult {
  /** ยอดที่หักได้จริงหลังตัดเพดานทุกชั้น */
  total: number;
  /** ยอดที่กรอกมาทั้งหมดก่อนตัดเพดาน */
  entered: number;
  /** รายการที่ถูกตัดเพดาน — หน้าจอเอาไปเตือนว่ากรอกเกินสิทธิ์ */
  capped: { key: string; label: string; entered: number; allowed: number; reason: string }[];
}

/**
 * รวมค่าลดหย่อนตามลำดับเพดาน: รายการ → กลุ่ม → เงินบริจาค (10% ของยอดที่เหลือ)
 * ต้องคิดบริจาคเป็นลำดับสุดท้ายเสมอ เพราะฐาน 10% ของมันคือ "หลังหักลดหย่อนอื่นแล้ว"
 */
export const sumDeductions = (
  map: DeductionMap | undefined,
  /** เงินได้พึงประเมิน (ใช้กับเพดานแบบ % ของเงินได้) */
  assessableIncome: number,
  /** เงินได้หลังหักค่าใช้จ่ายและลดหย่อนอื่นแล้ว (ฐานของเพดานบริจาค 10%) */
  netBeforeDonation: number
): DeductionResult => {
  const m = map ?? {};
  const capped: DeductionResult['capped'] = [];
  let entered = 0;

  // ชั้นที่ 1: เพดานรายรายการ
  const perItem = new Map<string, number>();
  DEDUCTION_ITEMS.forEach((item) => {
    const raw = Math.max(0, m[item.key] || 0);
    if (raw <= 0) return;
    entered += raw;
    let allowed = raw * (item.multiplier ?? 1);
    const limits: number[] = [];
    if (item.cap != null) limits.push(item.cap);
    if (item.capPercentOfIncome != null) {
      limits.push((assessableIncome * item.capPercentOfIncome) / 100);
    }
    if (limits.length > 0) {
      const limit = Math.min(...limits);
      if (allowed > limit) {
        capped.push({ key: item.key, label: item.label, entered: raw, allowed: limit, reason: item.note });
        allowed = limit;
      }
    }
    perItem.set(item.key, allowed);
  });

  // ชั้นที่ 2: เพดานกลุ่ม — เกินแล้วตัดตามสัดส่วนที่แต่ละรายการมีส่วนร่วม
  (Object.keys(DEDUCTION_CAP_GROUPS) as DeductionCapGroup[]).forEach((g) => {
    const { cap, label } = DEDUCTION_CAP_GROUPS[g];
    const keys = DEDUCTION_ITEMS.filter((i) => i.capGroup === g).map((i) => i.key);
    const sum = keys.reduce((s, k) => s + (perItem.get(k) || 0), 0);
    if (sum <= cap) return;
    const ratio = cap / sum;
    keys.forEach((k) => {
      const v = perItem.get(k);
      if (v) perItem.set(k, v * ratio);
    });
    capped.push({
      key: g,
      label,
      entered: sum,
      allowed: cap,
      reason: `รวมทั้งกลุ่มหักได้ไม่เกิน ${cap.toLocaleString('th-TH')}`,
    });
  });

  // ชั้นที่ 3: เงินบริจาค ≤ 10% ของเงินได้หลังหักลดหย่อนอื่น
  const donationKeys = DEDUCTION_ITEMS.filter((i) => i.capPercentOfNet != null).map((i) => i.key);
  const nonDonation = [...perItem.entries()]
    .filter(([k]) => !donationKeys.includes(k))
    .reduce((s, [, v]) => s + v, 0);
  const donationEntered = donationKeys.reduce((s, k) => s + (perItem.get(k) || 0), 0);
  const donationBase = Math.max(0, netBeforeDonation - nonDonation);
  const donationCap = donationBase * 0.1;
  const donationAllowed = Math.min(donationEntered, donationCap);
  if (donationEntered > donationCap) {
    capped.push({
      key: 'donation',
      label: 'เงินบริจาครวม',
      entered: donationEntered,
      allowed: donationCap,
      reason: 'หักได้ไม่เกิน 10% ของเงินได้หลังหักค่าใช้จ่ายและลดหย่อนอื่น',
    });
  }

  return { total: nonDonation + donationAllowed, entered, capped };
};

