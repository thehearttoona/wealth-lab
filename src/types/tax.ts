export interface TaxYearFacts {
  /** ปีนี้ผ่อนบ้านอยู่ไหม — สิทธิ์ดอกเบี้ยบ้าน 100,000 */
  hasHomeLoan?: boolean;
  /** ปีนี้เป็นผู้ประกันตน ม.33 ไหม — ถ้าใช่จะสมัคร กอช. ไม่ได้ */
  isSocialSecurityMember?: boolean;
  /** ปีนี้มีกองทุนสำรองเลี้ยงชีพ/กบข. กับที่ทำงานไหม */
  hasProvidentFund?: boolean;
  /** ปีนี้มีค่าฝากครรภ์/คลอดบุตรไหม */
  hasMaternity?: boolean;
  /** อยู่ในไทยครบ 180 วันในปีภาษีนี้ไหม — เงื่อนไขของเงินได้ต่างประเทศ (หุ้นนอก/คริปโต) */
  residentInThailand?: boolean;
}

