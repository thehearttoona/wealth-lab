// ── "เป้าหมายใหญ่สุดของชีวิต" — บันไดเงินก้อนที่ตั้งไว้เป็นด่าน ๆ ──
//
// ต่างจากเป้าหมายอีกสองอันในแอปตรงที่ **วัดจากความมั่งคั่งสุทธิทั้งก้อน** ไม่ใช่เฉพาะพอร์ต:
//   · `portfolio_goals`  = เป้ามูลค่าพอร์ต (เฉพาะเงินลงทุน)
//   · `purchase_goals`   = ของรางวัลที่ปลดล็อกด้วยกำไรที่ขายจริง
//   · `life_goals` (นี่)  = เงินทั้งชีวิต = พอร์ต + เงินสด − หนี้
//
// เป็น "บันได" ไม่ใช่เป้าเดียว เพราะถึงเป้าใหญ่แล้วชีวิตไม่ได้จบ — ผ่านด่านแล้วตั้งด่านใหม่
// ด่านที่ผ่านแล้วต้องเก็บไว้เป็นประวัติ ไม่ใช่เขียนทับ (มันคือหลักฐานว่ามาไกลแค่ไหน
// และเป็นตัวที่ใช้เลื่อนขั้นของน้องหมุด — ดู utils/lifeGoal.ts)

export interface LifeGoal {
  id: string;
  /** ชื่อด่าน เช่น "ล้านแรก" "เงินก้อนซื้อบ้าน" "อิสระทางการเงิน" */
  name: string;
  /** ยอดความมั่งคั่งสุทธิที่ถือว่าผ่านด่านนี้ (บาท) */
  targetTHB: number;
  /** ลำดับด่าน — เลขน้อยมาก่อน */
  level: number;
  /** null = ยังไม่ผ่าน · มีค่า = ผ่านแล้ววันไหน (YYYY-MM-DD) */
  achievedAt?: string;
  note?: string;
  createdAt: string;
}

