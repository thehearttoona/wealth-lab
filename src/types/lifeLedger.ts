//
// นี่คือ **บัญชีเดินสะพัด ไม่ใช่โควตารายเดือน** และความต่างนั้นคือทั้งเรื่อง:
//
//   โควตารายเดือน = "เดือนนี้ต้องทำกำไรให้ได้ ฿X"  → มีเส้นตาย → วันที่ 30 ต้องขายให้ครบเป้า
//   บัญชีเดินสะพัด = "ตอนนี้ค้างอยู่ ฿X (Y เดือน)" → ไม่มีเส้นตาย → ขายตอนรอบถึงเป้าเหมือนเดิม
//
// ยอดค้างไม่รีเซ็ตและไม่มีวันครบกำหนด มันแค่รอให้กำไรก้อนถัดไปมาหัก — ซึ่งจะมาตอนที่
// รอบลงทุนถึงเป้าของมันเอง ไม่ใช่ตอนสิ้นเดือน จังหวะขายจึงยังมาจากราคา ไม่ใช่ปฏิทิน
// (เหตุผลเดียวกับที่ utils/powderFlow.ts ห้ามให้ปฏิทินมาคุมขนาดไม้)
//
// เดือนเป็นหน่วยของ "การจด" เท่านั้น: จดเดือนละครั้งว่าชีวิตเรียกเก็บไปเท่าไหร่
// ไม่ต้องระบุวัน เพราะไม่มีอะไรในบัญชีนี้ถึงกำหนดเป็นวัน ๆ

/** หนึ่งเดือนที่จดไว้ — จ่ายไปเท่าไหร่ ไม่ใช่ควรจ่ายเท่าไหร่ */
export interface LedgerMonth {
  /** 'YYYY-MM' — คีย์จริงของแถว ผู้ใช้หนึ่งคนมีเดือนละแถวเท่านั้น */
  month: string;
  /** ค่าเสื่อมของเดือนนั้น (ยอดที่ต้องกันตาม utils/lifeCost) */
  depreciationTHB: number;
  /** ค่าใช้จ่ายประจำของเดือนนั้น (บิลที่กรอกจริง ไม่ใช่ยอดอ้างอิง) */
  billsTHB: number;
  note?: string;
  /** จดเมื่อไหร่ — ไว้บอกว่าตัวเลขนี้จดตอนนั้นหรือแก้ทีหลัง */
  recordedAt: string;
}

/** ชื่อเดือนแบบไทยจากคีย์ 'YYYY-MM' — ใช้ทั้งในลิสต์และในข้อความยืนยัน */
export const MONTH_LABELS_TH = [
  'ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.',
  'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.',
];

export const monthLabelTH = (month: string): string => {
  const m = /^(\d{4})-(\d{2})$/.exec(month || '');
  if (!m) return month || '—';
  const idx = Number(m[2]) - 1;
  const be = Number(m[1]) + 543;
  return `${MONTH_LABELS_TH[idx] ?? m[2]} ${`${be}`.slice(2)}`;
};
