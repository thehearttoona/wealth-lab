-- ค่าธรรมเนียม "ชั้นสกุลเงิน" + สกุลของค่าธรรมเนียมขั้นต่ำฝั่งแพลตฟอร์ม
-- รันที่ Supabase SQL editor / idempotent: รันซ้ำได้ไม่พัง
--
-- ทำไมต้องมีชั้นสกุลเงินเพิ่มจาก sql/user_platforms_fee.sql:
--   โบรกหุ้นไทยหลายเจ้าคิดเรตใกล้เคียงกันหมด บังคับให้พิมพ์เลขเดิมซ้ำทุกเจ้าคือ
--   ความ manual ที่ไม่ได้อะไรกลับมา และพอลืมตั้งสักเจ้า ราคาคุ้มทุนของไม้ที่ซื้อผ่าน
--   เจ้านั้นจะขาดค่าธรรมเนียมไปเงียบ ๆ
--   ลำดับที่โค้ดใช้: แพลตฟอร์ม (ถ้าตั้ง) → สกุลเงิน (ถ้าตั้ง) → ไม่รู้ (ดู utils/tradeFee.ts)
--
-- ไม่ตั้ง (null) ต่างจาก 0: null = ยังไม่รู้ / 0 = ฟรีจริง ๆ — อย่าใส่ default 0

alter table if exists public.user_currencies
  -- % ของมูลค่าที่ซื้อขายต่อ 1 คำสั่ง สำหรับตลาดที่ซื้อขายด้วยสกุลนี้
  add column if not exists fee_percent numeric,
  -- ขั้นต่ำต่อคำสั่ง **ในหน่วยของสกุลนั้นเอง** (USD = ดอลลาร์ ไม่ใช่บาท)
  add column if not exists fee_min numeric;

alter table if exists public.user_platforms
  -- สกุลของ fee_min_thb — null = บาท (ข้อมูลเก่าทั้งหมดคือบาท)
  -- มีไว้เพราะโบรกต่างประเทศคิดขั้นต่ำเป็นดอลลาร์ (IBKR $1/คำสั่ง) การบังคับกรอกเป็นบาท
  -- แปลว่าต้องแปลงเองทุกครั้งที่เรตขยับ ซึ่งไม่มีใครทำจริง
  add column if not exists fee_min_currency text;
